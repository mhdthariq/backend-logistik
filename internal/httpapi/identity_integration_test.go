func apiCall(t *testing.T, app *fiber.App, method, path, body, token, corp string, status int) map[string]any {
	t.Helper()
	req := httptest.NewRequest(method, path, strings.NewReader(body))
	req.Header.Set("Content-Type", "application/json")
	if token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}
	if corp != "" {
		req.Header.Set("x-corp-id", corp)
	}
	response, err := app.Test(req, fiber.TestConfig{Timeout: 10 * time.Second})
	if err != nil {
		t.Fatal(err)
	}
	defer func() {
		if err := response.Body.Close(); err != nil {
			t.Error(err)
		}
	}()
	var decoded map[string]any
	if err := json.NewDecoder(response.Body).Decode(&decoded); err != nil {
		t.Fatal(err)
	}
	if response.StatusCode != status {
		t.Fatalf("%s %s = %d, want %d: %v", method, path, response.StatusCode, status, decoded)
	}
	return decoded
}

func loginAs(t *testing.T, app *fiber.App, username, corp string) string {
	t.Helper()
	result := apiCall(t, app, "POST", "/api/v1/auth/login", `{"username":"`+username+`","password":"pässword-123"}`, "", corp, 200)
	return result["data"].(map[string]any)["token"].(string)
}

func TestIdentityPostgres(t *testing.T) {
	db := disposableDB(t)
	seedIdentity(t, db)
	registry := tenant.New(tenant.Config{DatabaseURL: db.dsn, Mode: "development"})
	t.Cleanup(registry.Close)
	app := httpapi.NewWithTenants(slog.New(slog.NewTextHandler(io.Discard, nil)), registry)
	owner := loginAs(t, app, "owner", "")
	t.Run("login contracts", func(t *testing.T) {
		for _, body := range []string{`{`, `{}`, `null`, `{"username":" "}`} {
			result := apiCall(t, app, "POST", "/api/v1/auth/login", body, "", "", 422)
			if result["errors"].(map[string]any)["username"] == nil {
				t.Fatal("missing field errors")
			}
		}
		apiCall(t, app, "POST", "/api/v1/auth/login", `{"username":"worker","password":"incorrect"}`, "", "", 401)
		result := apiCall(t, app, "POST", "/api/v1/auth/login", `{"username":" Worker ","password":"pässword-123"}`, "", "", 200)["data"].(map[string]any)
		u := result["user"].(map[string]any)
		if len(u["permissions"].([]any)) != 1 || u["employeeId"] != nil || u["warehouseId"] != nil || u["partnerId"] != nil || u["passwordHash"] != nil {
			t.Fatalf("login contract differs: %v", u)
		}
		token := result["token"].(string)
		me := apiCall(t, app, "GET", "/api/v1/auth/me", "", token, "", 200)["data"].(map[string]any)
		if len(me["permissions"].([]any)) != 2 {
			t.Fatal("hydrated session missing direct permissions")
		}
		var stored string
		if err := db.pool.QueryRow(context.Background(), `SELECT token FROM "SessionToken" WHERE token=$1`, identity.TokenHash(token)).Scan(&stored); err != nil {
			t.Fatal(err)
		}
		apiCall(t, app, "GET", "/api/v1/users", "", token, "", 200)
		apiCall(t, app, "GET", "/api/v1/roles", "", token, "", 403)
		apiCall(t, app, "POST", "/api/v1/auth/logout", "", token, "", 200)
		apiCall(t, app, "GET", "/api/v1/auth/me", "", token, "", 401)
		apiCall(t, app, "POST", "/api/v1/auth/logout", "", token, "", 200)
	})
	t.Run("inherited owner hydration", func(t *testing.T) {
		result := apiCall(t, app, "POST", "/api/v1/auth/login", `{"username":"inherited","password":"pässword-123"}`, "", "", 200)["data"].(map[string]any)
		if result["user"].(map[string]any)["isOwner"] != false {
			t.Fatal("login must preserve raw owner flag")
		}
		me := apiCall(t, app, "GET", "/api/v1/auth/me", "", result["token"].(string), "", 200)["data"].(map[string]any)
		if me["isOwner"] != true || me["permissions"].([]any)[0] != "*" {
			t.Fatal("owner role not inherited")
		}
	})
	t.Run("Node session expiry and inactive users", func(t *testing.T) {
		for _, tt := range []struct {
			token   string
			expires time.Time
			user    int
			status  int
		}{
			{"node-fixture", time.Now().Add(time.Hour), 2, 200}, {"expired-fixture", time.Now().Add(-time.Hour), 2, 401},
		} {
			if _, err := db.pool.Exec(context.Background(), `INSERT INTO "SessionToken" (token,"userId","expiresAt") VALUES ($1,$2,$3)`, identity.TokenHash(tt.token), tt.user, tt.expires); err != nil {
				t.Fatal(err)
			}
			apiCall(t, app, "GET", "/api/v1/auth/me", "", tt.token, "", tt.status)
		}
		if _, err := db.pool.Exec(context.Background(), `UPDATE "User" SET "isActive"=false WHERE id=2`); err != nil {
			t.Fatal(err)
		}
		apiCall(t, app, "GET", "/api/v1/auth/me", "", "node-fixture", "", 401)
		apiCall(t, app, "POST", "/api/v1/auth/login", `{"username":"worker","password":"pässword-123"}`, "", "", 401)
		if _, err := db.pool.Exec(context.Background(), `UPDATE "User" SET "isActive"=true WHERE id=2`); err != nil {
			t.Fatal(err)
		}
	})
	t.Run("roles and rollback", func(t *testing.T) {
		role := apiCall(t, app, "POST", "/api/v1/roles", `{"name":"Café Ops","permissionIds":[1,2]}`, owner, "", 200)["data"].(map[string]any)
		id := int(role["id"].(float64))
		path := fmt.Sprintf("/api/v1/roles/%d", id)
		if role["slug"] != "cafe-ops" || len(role["permissions"].([]any)) != 2 {
			t.Fatal("role shape differs")
		}
		apiCall(t, app, "PUT", path, `{"name":"Must Roll Back","permissionIds":[999]}`, owner, "", 422)
		var name string
		if err := db.pool.QueryRow(context.Background(), `SELECT name FROM "Role" WHERE id=$1`, id).Scan(&name); err != nil {
			t.Fatal(err)
		}
		if name != "Café Ops" {
			t.Fatal("failed permission edit persisted role changes")
		}
		apiCall(t, app, "PUT", path+"/permissions", `{"permissionIds":[3]}`, owner, "", 200)
		apiCall(t, app, "PUT", path, `{"name":"Operations"}`, owner, "", 200)
		apiCall(t, app, "GET", "/api/v1/roles", "", owner, "", 200)
		apiCall(t, app, "DELETE", "/api/v1/roles/1", "", owner, "", 422)
		apiCall(t, app, "DELETE", path, "", owner, "", 200)
	})
	t.Run("employees and users", func(t *testing.T) {
		e := apiCall(t, app, "POST", "/api/v1/employees", `{"name":"Courier","phone":"123"}`, owner, "", 200)["data"].(map[string]any)
		eid := int(e["id"].(float64))
		ep := fmt.Sprintf("/api/v1/employees/%d", eid)
		if e["employeeNumber"] != "EMP-000001" {
			t.Fatal("wrong employee code")
		}
		apiCall(t, app, "PUT", ep, `{"position":"Courier"}`, owner, "", 200)
		u := apiCall(t, app, "POST", "/api/v1/users", fmt.Sprintf(`{"username":"newcourier","name":"New Courier","password":"test-password","employeeId":%d,"roleIds":[2],"permissionIds":[2]}`, eid), owner, "", 200)["data"].(map[string]any)
		if _, exists := u["passwordHash"]; exists {
			t.Fatal("password hash exposed")
		}
		uid := int(u["id"].(float64))
		up := fmt.Sprintf("/api/v1/users/%d", uid)
		apiCall(t, app, "PUT", up, `{"name":"Changed","permissionIds":[999]}`, owner, "", 422)
		var name string
		if err := db.pool.QueryRow(context.Background(), `SELECT name FROM "User" WHERE id=$1`, uid).Scan(&name); err != nil {
			t.Fatal(err)
		}
		if name != "New Courier" {
			t.Fatal("failed user edit persisted")
		}
		apiCall(t, app, "PUT", up, `{"name":"Updated Courier","roleIds":[2],"permissionIds":[1,2]}`, owner, "", 200)
		apiCall(t, app, "GET", "/api/v1/employees?search=Courier&include_inactive=false", "", owner, "", 200)
		apiCall(t, app, "DELETE", ep, "", owner, "", 200)
		var active bool
		if err := db.pool.QueryRow(context.Background(), `SELECT "isActive" FROM "User" WHERE id=$1`, uid).Scan(&active); err != nil {
			t.Fatal(err)
		}
		if active {
			t.Fatal("employee disable did not disable linked user")
		}
		apiCall(t, app, "DELETE", up, "", owner, "", 200)
		apiCall(t, app, "DELETE", "/api/v1/users/1", "", owner, "", 422)
	})
	t.Run("partner creation rollback and wallet", func(t *testing.T) {
		apiCall(t, app, "POST", "/api/v1/users", `{"username":"badpartner","name":"Partner","password":"test-password","roleIds":[3],"warehouseId":999}`, owner, "", 422)
		var count int
		if err := db.pool.QueryRow(context.Background(), `SELECT count(*) FROM "User" WHERE username='badpartner'`).Scan(&count); err != nil {
			t.Fatal(err)
		}
		if count != 0 {
			t.Fatal("invalid partner left partial user")
		}
		u := apiCall(t, app, "POST", "/api/v1/users", `{"username":"partner","name":"Partner","password":"test-password","roleIds":[3]}`, owner, "", 200)["data"].(map[string]any)
		if u["partnerType"] != "MARKETING" {
			t.Fatal("missing partner profile")
		}
		if err := db.pool.QueryRow(context.Background(), `SELECT count(*) FROM "Wallet" WHERE "partnerId"=$1`, u["partnerId"]).Scan(&count); err != nil {
			t.Fatal(err)
		}
		if count != 1 {
			t.Fatal("missing partner wallet")
		}
	})
	t.Run("self profile", func(t *testing.T) {
		apiCall(t, app, "GET", "/api/v1/profile", "", owner, "", 200)
		apiCall(t, app, "PUT", "/api/v1/profile", `{}`, owner, "", 200)
		apiCall(t, app, "PUT", "/api/v1/profile", `{"newPassword":"new-password","currentPassword":"incorrect"}`, owner, "", 422)
		apiCall(t, app, "PUT", "/api/v1/profile", `{"name":"Owner Updated","newPassword":"new-password","currentPassword":"pässword-123"}`, owner, "", 200)
		apiCall(t, app, "POST", "/api/v1/auth/login", `{"username":"owner","password":"new-password"}`, "", "", 200)
	})
}

func TestTwoTenantIsolation(t *testing.T) {
	a, other := disposableDB(t), disposableDB(t)
	seedIdentity(t, a)
	seedIdentity(t, other)
	if _, err := other.pool.Exec(context.Background(), `UPDATE "User" SET name='Other Company Owner' WHERE id=1`); err != nil {
		t.Fatal(err)
	}
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		db := a
		if r.URL.Query().Get("KdCustomer") == "B" {
			db = other
		}
		u, err := url.Parse(db.dsn)
		if err != nil {
			t.Error(err)
			return
		}
		payload := map[string]any{"Status": "Ok", "Data": map[string]any{"KdCustomer": r.URL.Query().Get("KdCustomer"), "NamaCustomer": db.name, "Server": u.Host, "Db": db.name, "Username": u.User.Username()}}
		if err := json.NewEncoder(w).Encode(payload); err != nil {
			t.Error(err)
		}
	}))
	defer server.Close()
	registry := tenant.New(tenant.Config{Mode: "production", LicenseURL: server.URL, LicenseKey: "test", LicenseToken: "test", LicenseApplication: "test", MaxPools: 2})
	defer registry.Close()
	app := httpapi.NewWithTenants(nil, registry)
	tokenA, tokenB := loginAs(t, app, "owner", "A"), loginAs(t, app, "owner", "B")
	apiCall(t, app, "GET", "/api/v1/auth/me", "", tokenA, "B", 401)
	apiCall(t, app, "GET", "/api/v1/auth/me", "", tokenB, "A", 401)
	var wg sync.WaitGroup
	for i := 0; i < 8; i++ {
		wg.Go(func() {
			aUser := apiCall(t, app, "GET", "/api/v1/auth/me", "", tokenA, "A", 200)["data"].(map[string]any)
			bUser := apiCall(t, app, "GET", "/api/v1/auth/me", "", tokenB, "B", 200)["data"].(map[string]any)
			if aUser["name"] == bUser["name"] {
				t.Error("tenant identity leaked")
			}
		})
	}
	wg.Wait()
}
