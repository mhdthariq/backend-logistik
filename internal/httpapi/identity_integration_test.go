func TestPrismaMigrationsContainCurrentColumns(t *testing.T) {
	db := disposableDB(t)
	schema, err := os.ReadFile("../../../kirimku/prisma/schema.prisma")
	if err != nil {
		t.Fatal(err)
	}
	rows, err := db.pool.Query(context.Background(), `SELECT table_name,column_name FROM information_schema.columns WHERE table_schema='public'`)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	columns := map[string]bool{}
	for rows.Next() {
		var table, column string
		if err := rows.Scan(&table, &column); err != nil {
			t.Fatal(err)
		}
		columns[table+"."+column] = true
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	models := regexp.MustCompile(`(?ms)^model (\w+) \{\r?\n(.*?)^\}`).FindAllStringSubmatch(string(schema), -1)
	scalar := regexp.MustCompile(`(?m)^\s+(\w+)\s+(?:String|Int|Float|Boolean|DateTime|Decimal|Json|BigInt|Bytes)(?:\?|\[\])?\s`)
	for _, model := range models {
		for _, field := range scalar.FindAllStringSubmatch(model[2], -1) {
			key := model[1] + "." + field[1]
			if !columns[key] {
				t.Errorf("Prisma migration history is missing %s", key)
			}
		}
	}
	// The reconciliation migration also runs on databases previously using db push.
	sql, err := os.ReadFile("../../../kirimku/prisma/migrations/20261104120000_capacity_settings_schema_parity/migration.sql")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := db.pool.Exec(context.Background(), string(sql)); err != nil {
		t.Fatalf("schema reconciliation is not idempotent: %v", err)
	}
}

func disposableDB(t *testing.T) testDatabase {
	t.Helper()
	adminDSN := os.Getenv("TEST_DATABASE_URL")
	if adminDSN == "" {
		t.Skip("TEST_DATABASE_URL required for disposable PostgreSQL integration")
	}
	ctx := context.Background()
	admin, err := pgx.Connect(ctx, adminDSN)
	if err != nil {
		t.Fatal(err)
	}
	name := fmt.Sprintf("novalogistik_test_%d", time.Now().UnixNano())
	if _, err := admin.Exec(ctx, `CREATE DATABASE `+pgx.Identifier{name}.Sanitize()); err != nil {
		t.Fatal(err)
	}
	u, err := url.Parse(adminDSN)
	if err != nil {
		t.Fatal(err)
	}
	u.Path = "/" + name
	cfg, err := pgxpool.ParseConfig(u.String())
	if err != nil {
		t.Fatal(err)
	}
	cfg.ConnConfig.DefaultQueryExecMode = pgx.QueryExecModeSimpleProtocol
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		pool.Close()
		// Only the unique database created by this test is ever dropped.
		if _, err := admin.Exec(ctx, `DROP DATABASE `+pgx.Identifier{name}.Sanitize()+` WITH (FORCE)`); err != nil {
			t.Error(err)
		}
		if err := admin.Close(ctx); err != nil {
			t.Error(err)
		}
	})
	migrations, err := filepath.Glob("../../../kirimku/prisma/migrations/*/migration.sql")
	if err != nil {
		t.Fatal(err)
	}
	if len(migrations) == 0 {
		t.Fatal("legacy Prisma migrations not found")
	}
	for _, file := range migrations {
		sql, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := pool.Exec(ctx, string(sql)); err != nil {
			t.Fatalf("Prisma migration %s: %v", filepath.Base(filepath.Dir(file)), err)
		}
	}
	return testDatabase{pool, u.String(), name}
}

